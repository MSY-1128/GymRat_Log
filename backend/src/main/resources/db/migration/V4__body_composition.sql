-- 체성분(인바디 등) 기록 + 기초대사량 계산 방식·단백질 목표

CREATE TABLE body_composition (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    measured_on         DATE          NOT NULL,
    weight_kg           NUMERIC(5, 1) NOT NULL CHECK (weight_kg BETWEEN 30 AND 350),
    body_fat_pct        NUMERIC(4, 1) CHECK (body_fat_pct BETWEEN 3 AND 70),
    skeletal_muscle_kg  NUMERIC(5, 1) CHECK (skeletal_muscle_kg BETWEEN 5 AND 100),
    measured_bmr_kcal   INTEGER       CHECK (measured_bmr_kcal BETWEEN 500 AND 5000),
    visceral_fat_level  INTEGER       CHECK (visceral_fat_level BETWEEN 1 AND 30),
    created_at          TIMESTAMPTZ   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    -- 골격근량은 체중보다 작아야 한다
    CONSTRAINT body_composition_muscle_check CHECK (skeletal_muscle_kg IS NULL OR skeletal_muscle_kg < weight_kg)
);
-- 하루 한 번(같은 날 다시 재면 수정)
CREATE UNIQUE INDEX uq_body_composition_user_date ON body_composition (user_id, measured_on);

ALTER TABLE profile ADD COLUMN bmr_method VARCHAR(10) NOT NULL DEFAULT 'FORMULA'
    CHECK (bmr_method IN ('FORMULA', 'BODY_FAT', 'MEASURED'));
ALTER TABLE profile ADD COLUMN protein_g_per_kg_lean NUMERIC(3, 1)
    CHECK (protein_g_per_kg_lean BETWEEN 0.8 AND 3.0);
