-- 로그인 + 사용자별 데이터 분리

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL
);
-- 아이디는 대소문자 구분 없이 유일
CREATE UNIQUE INDEX uq_app_user_username ON app_user (lower(username));

-- 사용자별 데이터. 기존(로그인 도입 전) 행은 user_id가 비어 있고, 처음 가입한 계정이 이어받는다.
ALTER TABLE profile ADD COLUMN user_id BIGINT REFERENCES app_user (id) ON DELETE CASCADE;
ALTER TABLE profile ADD CONSTRAINT uq_profile_user UNIQUE (user_id);

ALTER TABLE meal_entry ADD COLUMN user_id BIGINT REFERENCES app_user (id) ON DELETE CASCADE;
CREATE INDEX idx_meal_entry_user_date ON meal_entry (user_id, entry_date, id);

ALTER TABLE exercise_entry ADD COLUMN user_id BIGINT REFERENCES app_user (id) ON DELETE CASCADE;
CREATE INDEX idx_exercise_entry_user_date ON exercise_entry (user_id, entry_date, id);

-- 사용자가 직접 등록한 음식(USER)은 등록한 사람만 본다. DEMO·MFDS 음식은 모두가 공유한다.
ALTER TABLE food ADD COLUMN owner_id BIGINT REFERENCES app_user (id) ON DELETE CASCADE;
ALTER TABLE food ADD CONSTRAINT food_owner_source_check CHECK (owner_id IS NULL OR source = 'USER');
CREATE INDEX idx_food_owner ON food (owner_id);
