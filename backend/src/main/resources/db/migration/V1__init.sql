-- FitLog 초기 스키마 (PostgreSQL)

CREATE TABLE profile (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    age               INTEGER       NOT NULL CHECK (age BETWEEN 19 AND 100),
    sex_for_formula   VARCHAR(10)   CHECK (sex_for_formula IN ('MALE', 'FEMALE')),
    height_cm         NUMERIC(5, 1) NOT NULL CHECK (height_cm BETWEEN 100 AND 250),
    weight_kg         NUMERIC(5, 1) NOT NULL CHECK (weight_kg BETWEEN 30 AND 350),
    activity_factor   NUMERIC(4, 3) NOT NULL CHECK (activity_factor IN (1.2, 1.375, 1.55, 1.725, 1.9)),
    goal              VARCHAR(10)   NOT NULL CHECK (goal IN ('LOSE', 'MAINTAIN', 'GAIN')),
    daily_target_kcal INTEGER       CHECK (daily_target_kcal BETWEEN 1 AND 10000),
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ   NOT NULL
);

CREATE TABLE food (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    kcal          NUMERIC(7, 2) NOT NULL CHECK (kcal >= 0),
    carbs_g       NUMERIC(7, 2) NOT NULL CHECK (carbs_g >= 0),
    protein_g     NUMERIC(7, 2) NOT NULL CHECK (protein_g >= 0),
    fat_g         NUMERIC(7, 2) NOT NULL CHECK (fat_g >= 0),
    serving_grams NUMERIC(6, 1) CHECK (serving_grams > 0 AND serving_grams <= 5000),
    source        VARCHAR(10)   NOT NULL CHECK (source IN ('DEMO', 'USER')),
    sample_id     BIGINT,
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_food_name ON food (lower(name));

CREATE TABLE exercise (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)  NOT NULL,
    met        NUMERIC(5, 2) NOT NULL CHECK (met > 0),
    source     VARCHAR(10)   NOT NULL CHECK (source IN ('DEMO', 'USER')),
    sample_id  BIGINT,
    created_at TIMESTAMPTZ   NOT NULL,
    updated_at TIMESTAMPTZ   NOT NULL
);

CREATE TABLE meal_entry (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_date              DATE          NOT NULL,
    meal_type               VARCHAR(10)   NOT NULL CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK')),
    food_id                 BIGINT        NOT NULL REFERENCES food (id),
    grams                   NUMERIC(6, 1) NOT NULL CHECK (grams > 0 AND grams <= 5000),
    food_name_snapshot      VARCHAR(100)  NOT NULL,
    kcal_per100_snapshot    NUMERIC(7, 2) NOT NULL,
    carbs_per100_snapshot   NUMERIC(7, 2) NOT NULL,
    protein_per100_snapshot NUMERIC(7, 2) NOT NULL,
    fat_per100_snapshot     NUMERIC(7, 2) NOT NULL,
    created_at              TIMESTAMPTZ   NOT NULL,
    updated_at              TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_meal_entry_date ON meal_entry (entry_date, id);
CREATE INDEX idx_meal_entry_food ON meal_entry (food_id);

CREATE TABLE exercise_entry (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_date         DATE          NOT NULL,
    exercise_id        BIGINT        NOT NULL REFERENCES exercise (id),
    minutes            INTEGER       NOT NULL CHECK (minutes BETWEEN 1 AND 1440),
    name_snapshot      VARCHAR(100)  NOT NULL,
    weight_kg_snapshot NUMERIC(5, 1) NOT NULL,
    met_snapshot       NUMERIC(5, 2) NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_exercise_entry_date ON exercise_entry (entry_date, id);
CREATE INDEX idx_exercise_entry_exercise ON exercise_entry (exercise_id);

-- demo seed 1회 적용 기록. 삭제된 seed를 재시작 시 복원하지 않기 위해 사용한다.
CREATE TABLE seed_history (
    seed_key   VARCHAR(50) PRIMARY KEY,
    status     VARCHAR(20) NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL
);
